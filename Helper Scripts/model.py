    reg = reg.permute(0, 2, 3, 1).reshape(-1, 4)
    # Step 3: Apply post-processing
    # - select best class
    # - filter low scores
    # - apply NMS
    return simple_test_bboxes(cls, reg, score_thr, iou_thr)

