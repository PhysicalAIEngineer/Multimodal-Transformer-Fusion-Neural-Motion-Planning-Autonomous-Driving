# Forward pass for a single feature level
# -------------------------------------------------------------------------
def forward_single(self, feat):
    """
    Forward computation for a single feature map.

    Args:
        feat (Tensor):
            Feature map of shape (B, C, H, W)

    Returns:
        Tuple of predictions:
            - center_heatmap_pred: (B, num_classes, H, W)
            - wh_pred: (B, 2, H, W)
            - offset_pred: (B, 2, H, W)
            - yaw_class_pred: (B, num_dir_bins, H, W)
            - yaw_res_pred: (B, 1, H, W)
            - velocity_pred: (B, 1, H, W)
            - brake_pred: (B, 2, H, W)
    """
    # Heatmap prediction (object center probability)
    # Sigmoid converts logits → probabilities in range [0, 1]
    center_heatmap_pred = self.heatmap_head(feat).sigmoid()
    # Bounding box size prediction (width, height)
    wh_pred = self.wh_head(feat)
    # Center offset prediction (sub-pixel refinement)
    offset_pred = self.offset_head(feat)
    # ---------------------------------------------------------------------
    # Yaw (orientation) prediction
    # ---------------------------------------------------------------------
    # Discrete orientation class (which direction bin)
    yaw_class_pred = self.yaw_class_head(feat)
    # Continuous residual to refine orientation
    yaw_res_pred = self.yaw_res_head(feat)
    # ---------------------------------------------------------------------
    # Additional attributes
    # ---------------------------------------------------------------------
    # Velocity prediction (object speed)
    velocity_pred = self.velocity_head(feat)
    # Brake prediction (binary classification: brake / no brake)
    brake_pred = self.brake_head(feat)
    # ---------------------------------------------------------------------
    # Return all predictions for this feature level
    # ---------------------------------------------------------------------
    return (center_heatmap_pred,wh_pred,offset_pred,yaw_class_pred,
            yaw_res_pred,velocity_pred,brake_pred)

