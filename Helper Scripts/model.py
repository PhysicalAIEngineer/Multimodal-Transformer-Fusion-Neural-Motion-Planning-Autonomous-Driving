# -------------------------------------------------------------------------
# Helper function to build a prediction head (branch)
# -------------------------------------------------------------------------
def _build_head(self, in_channel, feat_channel, out_channel):
    """
    Build a small convolutional head for a specific prediction task.
    Each head consists of:
    1. Conv layer (3x3) → extracts spatial features
    2. ReLU activation → introduces non-linearity
    3. Conv layer (1x1) → maps features to desired output channels
    Args:
        in_channel (int): Number of input feature channels.
        feat_channel (int): Number of intermediate feature channels.
        out_channel (int): Number of output channels (depends on task).
    Returns:
        nn.Sequential: A small CNN block used as a prediction head.
    """
    layer = nn.Sequential(
        # 3x3 convolution to process spatial features
        nn.Conv2d(in_channel, feat_channel, kernel_size=3, padding=1),
        # Activation function (inplace saves memory)
        nn.ReLU(inplace=True),
        # 1x1 convolution to produce final outputs
        nn.Conv2d(feat_channel, out_channel, kernel_size=1)
    )
    return layer
