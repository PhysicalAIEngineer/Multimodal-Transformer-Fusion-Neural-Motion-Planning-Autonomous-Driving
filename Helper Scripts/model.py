def transpose_and_gather_feat(feat, ind):
    """
    Extract features at specific spatial locations (indices).

    Args:
        feat (Tensor): shape (B, C, H, W)
                       feature map from network
        ind (Tensor): shape (B, K)
                      flattened indices of positions (e.g., object centers)

    Returns:
        Tensor: gathered features of shape (B, K, C)
    """
    # ----------------------------------------
    # Step 1: Rearrange dimensions
    # (B, C, H, W) → (B, H, W, C)
    # This makes spatial dimensions come before channels
    # ----------------------------------------
    feat = feat.permute(0, 2, 3, 1).contiguous()
    # ----------------------------------------
    # Step 2: Flatten spatial dimensions
    # (B, H, W, C) → (B, H*W, C)
    # Each spatial location becomes a row
    # ----------------------------------------
    feat = feat.view(feat.size(0), -1, feat.size(3))
    # ----------------------------------------
    # Step 3: Prepare indices for gathering
    # ind: (B, K) → (B, K, C)
    # Expand indices to match feature dimension
    # ----------------------------------------
    ind = ind.unsqueeze(2).expand(ind.size(0), ind.size(1), feat.size(2))
    # ----------------------------------------
    # Step 4: Gather features at specified indices
    # Select K positions from H*W locations
    # ----------------------------------------
    feat = feat.gather(1, ind)
    # Output shape: (B, K, C)
    return feat

