def normal_init(module, mean=0, std=1, bias=0):
    """
    Initialize the weights and bias of a neural network module.
    """
    # Check if the module has a weight parameter and it's not None
    if hasattr(module, 'weight') and module.weight is not None:
        # Initialize weights using normal (Gaussian) distribution
        # weight ~ N(mean, std)
        nn.init.normal_(module.weight, mean, std)
    # Check if the module has a bias parameter and it's not None
    if hasattr(module, 'bias') and module.bias is not None:
        # Initialize bias with a constant value
        nn.init.constant_(module.bias, bias)

