def inference_from_features(feats, model):
    """
    Perform inference from multi-scale feature maps.
    Args:
        feats: list of feature maps [(B, C, H, W), ...]
               typically from backbone/FPN
        model: detection head with method `forward_single`
    Returns:
        Tuple:
            - all_boxes: concatenated bounding boxes
            - all_scores: corresponding confidence scores
            - all_labels: predicted class labels
    """
    # Lists to store results from all feature levels
    all_boxes = []
    all_scores = []
    all_labels = []
    # ----------------------------------------
    # Loop over each feature map (multi-scale)
    # ----------------------------------------
    for feat in feats:
        # Get predictions for a single feature map
        # cls: (B, C, H, W) → class scores
        # reg: (B, 4, H, W) → bounding boxes
        cls, reg = model.forward_single(feat)
        # Extract dimensions
        B, C, H, W = cls.shape
        # Reshape classification output
        # (B, C, H, W) → (B, H, W, C) → (B*H*W, C)
        # Each spatial location becomes a detection
        cls = cls.permute(0, 2, 3, 1).reshape(-1, C)
        # Reshape regression output
        # (B, 4, H, W) → (B, H, W, 4) → (B*H*W, 4)
        reg = reg.permute(0, 2, 3, 1).reshape(-1, 4)
        # Apply post-processing (threshold + NMS)
        boxes, scores, labels = simple_test_bboxes(cls, reg)
        # Store results from this feature level
        all_boxes.append(boxes)
        all_scores.append(scores)
        all_labels.append(labels)
    # Combine results from all feature levels
    return (
        torch.cat(all_boxes),   # all detected boxes
        torch.cat(all_scores),  # all scores
        torch.cat(all_labels),  # all class labels
    )

