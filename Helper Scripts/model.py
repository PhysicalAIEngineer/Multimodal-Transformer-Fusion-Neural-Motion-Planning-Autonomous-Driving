def force_fp32(func):
    """
    Decorator to ensure all tensor inputs to a function are converted to float32.
    Useful when working with mixed precision (FP16), but certain operations
    require higher numerical stability in FP32.
    """
    def wrapper(*args, **kwargs):
        # Convert all positional arguments to float32 if they are tensors
        new_args = [a.float() if isinstance(a, torch.Tensor) else a for a in args]
        # Convert all keyword arguments to float32 if they are tensors
        new_kwargs = {k: v.float() if isinstance(v, torch.Tensor) else v for k, v in kwargs.items()}
        # Call the original function with converted arguments
        return func(*new_args, **new_kwargs)
    # Return the wrapped function
    return wrapper

def multi_apply(func, *args, **kwargs):
    """
    Apply a function to multiple inputs (like map) and group outputs by their type.
    """
    # Create a new function that includes kwargs (if provided)
    # This ensures func can be called with both args and kwargs
    pfunc = lambda *a: func(*a, **kwargs) if kwargs else func(*a)
    # Apply function to each set of inputs (like map)
    map_results = map(pfunc, *args)
    # Convert map object to list
    results = list(map_results)
    # Transpose the list of tuples zip(*results) converts:
    return tuple(map(list, zip(*results)))

