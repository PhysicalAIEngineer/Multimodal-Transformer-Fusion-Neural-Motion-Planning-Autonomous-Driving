class MyDenseHead(BaseDenseHead):
    """
    A simple dense detection head.
    Performs:
    - Feature processing
    - Classification (what object)
    - Regression (where object is)
    Supports multi-scale features (e.g., from FPN).
    """
    def __init__(self, in_channels, num_classes):
        # Initialize base class
        super().__init__()
        # Shared convolution layer: Reduces/learns features from backbone output
        self.conv = nn.Conv2d(in_channels, 64, 3, padding=1)
        # Classification layer: Outputs class scores for each spatial location
        self.cls_layer = nn.Conv2d(64, num_classes, 1)
        # Regression layer:Outputs bounding box values (x, y, w, h or x1, y1, x2, y2)
        self.reg_layer = nn.Conv2d(64, 4, 1)
        # Classification loss: Compares predicted class logits with ground truth labels
        self.cls_loss = nn.CrossEntropyLoss()
        # Regression loss: Measures difference between predicted and GT boxes
        self.reg_loss = nn.SmoothL1Loss()
    def forward(self, feats):
        """
        Forward pass over multi-scale feature maps.
        """
        outputs = []
        # Process each feature map independently
        for x in feats:
            # Shared feature extraction
            x = self.conv(x)
            # Predict class scores
            cls = self.cls_layer(x)
            # Predict bounding boxes
            reg = self.reg_layer(x)
            # Store predictions for this level
            outputs.append((cls, reg))
        return outputs
    def loss(self, preds, targets):
        """
        Compute total loss across all feature levels.
        """
        # accumulate classification loss
        loss_cls = 0
        # accumulate regression loss
        loss_reg = 0
        # Loop over each feature level
        for (cls, reg), (gt_cls, gt_reg) in zip(preds, targets):
            # Compute classification loss
            loss_cls += self.cls_loss(cls, gt_cls)
            # Compute bounding box regression loss
            loss_reg += self.reg_loss(reg, gt_reg)
        # Return both losses separately (useful for monitoring)
        return {"loss_cls": loss_cls,"loss_reg": loss_reg}
    def predict(self, preds):
        """
        Inference step: convert raw outputs into usable predictions.
        """
        results = []
        for cls, reg in preds:
            # convert logits → probabilities softmax across class dimension
            scores = torch.softmax(cls, dim=1)
            # append results for this feature level post-processing like NMS not yet applied
            results.append((scores, reg))
        return results

