def batched_nms_pytorch(boxes, scores, labels, iou_threshold):
    """
    Perform class-wise Non-Maximum Suppression (NMS).
    """
    # store final selected indices
    keep_indices = []
    # Get unique class labels (e.g., car, person, bike)
    unique_labels = labels.unique()
    # Apply NMS separately for each class
    for cls in unique_labels:
        # Create mask for current class
        cls_mask = labels == cls
        # Select boxes and scores belonging to this class
        cls_boxes = boxes[cls_mask]
        cls_scores = scores[cls_mask]
        # Apply standard NMS (removes overlapping boxes)
        cls_keep = nms(cls_boxes, cls_scores, iou_threshold)
        # Get original indices of these class-specific boxes
        original_indices = torch.nonzero(cls_mask).squeeze(1)
        # Map NMS-selected indices back to original indexing
        keep_indices.append(original_indices[cls_keep])
    # Concatenate indices from all classes
    return torch.cat(keep_indices)

