def get_local_maximum(heatmap, kernel=3):
    """
    Extract local maxima (peaks) from a heatmap.

    Args:
        heatmap (Tensor): shape (B, C, H, W) or (H, W)
        kernel (int): size of neighborhood to consider (default = 3)

    Returns:
        Tensor: heatmap with only local maxima retained (others set to 0)
    """
    # Compute padding so output size remains same after max pooling
    pad = (kernel - 1) // 2
    # Apply max pooling: For each pixel, replace it with the maximum value in its local neighborhood
    hmax = F.max_pool2d(heatmap, kernel_size=kernel, stride=1, padding=pad)
    # Create a mask: Keep only positions where original value == local maximum
    keep = (hmax == heatmap).float()
    # Multiply mask with heatmap:
    # - Local maxima → kept
    # - Non-max values → set to 0
    return heatmap * keep

