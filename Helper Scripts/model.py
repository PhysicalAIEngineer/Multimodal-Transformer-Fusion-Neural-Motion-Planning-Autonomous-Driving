# -------------------------------------------------------------------------
# Convert continuous angle → discrete class + residual
# -------------------------------------------------------------------------
def angle2class(self, angle):
    """
    Convert a continuous angle into:
    1. A discrete class (bin index)
    2. A small residual (offset from bin center)
    this is commonly used for orientation (yaw) prediction in detection tasks.
    Instead of directly regressing angle (hard problem), we:
    - Classify angle into bins (coarse prediction)
    - Regress small offset within that bin (fine prediction)
    Args:
        angle (Tensor):Angle values in radians (range: 0 to 2π or -π to π)
    Returns:
        tuple:
            angle_cls (Tensor): Discrete class index (bin number)
            angle_res (Tensor): Residual offset from bin center
    """
    # ---------------------------------------------------------------------
    # Normalize angle to range [0, 2π)
    # ---------------------------------------------------------------------
    angle = angle % (2 * np.pi)
    # ---------------------------------------------------------------------
    # Compute size of each bin
    # Example: if num_dir_bins = 4 → each bin = 90° (π/2)
    # ---------------------------------------------------------------------
    angle_per_class = 2 * np.pi / float(self.num_dir_bins)
    # ---------------------------------------------------------------------
    # Shift angle by half bin size
    # This aligns bins so that class centers are evenly spaced
    # ---------------------------------------------------------------------
    shifted_angle = (angle + angle_per_class / 2) % (2 * np.pi)
    # ---------------------------------------------------------------------
    # Compute discrete class (bin index)
    #
    # NOTE:
    # - Using trunc (towards zero) instead of floor
    # - Works same as floor because angle is always positive
    # - Keeps backward compatibility with older models
    # ---------------------------------------------------------------------
    angle_cls = torch.div(shifted_angle,angle_per_class,rounding_mode="trunc")
    # ---------------------------------------------------------------------
    # Compute residual (fine offset from bin center)
    # Formula: residual = actual angle - center of assigned bin
    # ---------------------------------------------------------------------
    angle_res = shifted_angle - (angle_cls * angle_per_class + angle_per_class / 2)
    # Return:
    # - class index (integer)
    # - residual (float)
    return angle_cls.long(), angle_res

# -------------------------------------------------------------------------
# Convert discrete class + residual → continuous angle
# -------------------------------------------------------------------------
def class2angle(self, angle_cls, angle_res, limit_period=True):
    """
    Decode angle from:
    - Discrete class (bin index)
    - Residual (offset within bin)

    This is the inverse operation of `angle2class`.

    Args:
        angle_cls (Tensor):
            Predicted angle class (bin index)
        angle_res (Tensor):
            Predicted residual (fine offset)
        limit_period (bool):
            If True, constrain output angle to [-π, π]

    Returns:
        Tensor:
            Decoded continuous angle in radians
    """
    # ---------------------------------------------------------------------
    # Compute size of each bin
    # ---------------------------------------------------------------------
    angle_per_class = 2 * np.pi / float(self.num_dir_bins)
    # ---------------------------------------------------------------------
    # Compute center angle of the predicted bin
    # ---------------------------------------------------------------------
    angle_center = angle_cls.float() * angle_per_class
    # ---------------------------------------------------------------------
    # Add residual to get final continuous angle
    # final_angle = bin_center + small_offset
    # ---------------------------------------------------------------------
    angle = angle_center + angle_res
    # ---------------------------------------------------------------------
    # Optionally normalize angle to range [-π, π]
    # This avoids discontinuity issues (e.g., 359° ≈ -1°)
    # ---------------------------------------------------------------------
    if limit_period:
        angle[angle > np.pi] -= 2 * np.pi
    # Return decoded angle
    return angle

# -------------------------------------------------------------------------
# Generate training targets from ground truth annotations
# -------------------------------------------------------------------------
def get_targets(self, gt_bboxes, gt_labels, gt_ignores, feat_shape):
    """
    Convert ground truth annotations into training targets for all heads.
    This function maps GT boxes from image space → feature map space
    and creates targets for:
        - Heatmap (object centers)
        - Width & Height
        - Offset
        - Yaw (class + residual)
        - Velocity
        - Brake
        - Weight mask
    Args:
        gt_bboxes (list[Tensor]):
            Ground truth boxes per image
            Format: (x_center, y_center, w, h, yaw, velocity, brake)
        gt_labels (list[Tensor]):
            Class labels per object
        gt_ignores (list[Tensor]):
            Boolean mask to ignore certain objects
        feat_shape (list[int]):
            Shape of feature map → [B, C, H, W]
    Returns:
        target_result (dict):
            Dictionary containing all training targets
        avg_factor (float):
            Normalization factor (number of positive samples)
    """
    # ---------------------------------------------------------------------
    # Get original LiDAR resolution and feature map size
    # ---------------------------------------------------------------------
    img_h = self.train_cfg.lidar_resolution_height
    img_w = self.train_cfg.lidar_resolution_width
    bs, _, feat_h, feat_w = feat_shape
    # Compute scaling ratios (image → feature map)
    width_ratio = float(feat_w / img_w)
    height_ratio = float(feat_h / img_h)
    # ---------------------------------------------------------------------
    # Initialize all target tensors with zeros
    # ---------------------------------------------------------------------
    center_heatmap_target = gt_bboxes[-1].new_zeros([bs, self.num_classes, feat_h, feat_w])
    wh_target = gt_bboxes[-1].new_zeros([bs, 2, feat_h, feat_w])
    offset_target = gt_bboxes[-1].new_zeros([bs, 2, feat_h, feat_w])
    yaw_class_target = gt_bboxes[-1].new_zeros([bs, 1, feat_h, feat_w]).long()
    yaw_res_target = gt_bboxes[-1].new_zeros([bs, 1, feat_h, feat_w])
    velocity_target = gt_bboxes[-1].new_zeros([bs, 1, feat_h, feat_w])
    brake_target = gt_bboxes[-1].new_zeros([bs, 1, feat_h, feat_w]).long()
    # Weight mask → indicates valid object locations
    wh_offset_target_weight = gt_bboxes[-1].new_zeros([bs, 2, feat_h, feat_w])
    # ---------------------------------------------------------------------
    # Process each image in batch
    # ---------------------------------------------------------------------
    for batch_id in range(bs):
        gt_bbox = gt_bboxes[0][batch_id]
        gt_label = gt_labels[0][batch_id]
        gt_ignore = gt_ignores[0][batch_id]
        # -----------------------------------------------------------------
        # Convert center coordinates to feature map scale
        # -----------------------------------------------------------------
        center_x = gt_bbox[:, [0]] * width_ratio
        center_y = gt_bbox[:, [1]] * width_ratio
        gt_centers = torch.cat((center_x, center_y), dim=1)
        # -----------------------------------------------------------------
        # Loop over each object
        # -----------------------------------------------------------------
        for j, ct in enumerate(gt_centers):
            # Skip ignored objects
            if gt_ignore[j]:
                continue
            # Integer location (grid cell)
            ctx_int, cty_int = ct.int()
            # Floating-point center
            ctx, cty = ct
            # Scale box size to feature map
            scale_box_h = gt_bbox[j, 3] * height_ratio
            scale_box_w = gt_bbox[j, 2] * width_ratio
            # -----------------------------------------------------------------
            # Generate Gaussian heatmap for object center
            # -----------------------------------------------------------------
            radius = gaussian_radius([scale_box_h, scale_box_w],min_overlap=0.1)
            radius = max(2, int(radius))
            # Class index
            ind = gt_label[j].long()
            # Draw Gaussian peak on heatmap
            gen_gaussian_target(center_heatmap_target[batch_id, ind],[ctx_int, cty_int],radius)
            # -----------------------------------------------------------------
            # Width & Height targets
            # -----------------------------------------------------------------
            wh_target[batch_id, 0, cty_int, ctx_int] = scale_box_w
            wh_target[batch_id, 1, cty_int, ctx_int] = scale_box_h
            # -----------------------------------------------------------------
            # Yaw (orientation) targets
            # -----------------------------------------------------------------
            yaw_class, yaw_res = self.angle2class(gt_bbox[j, 4])
            yaw_class_target[batch_id, 0, cty_int, ctx_int] = yaw_class
            yaw_res_target[batch_id, 0, cty_int, ctx_int] = yaw_res
            # -----------------------------------------------------------------
            # Velocity and brake targets
            # -----------------------------------------------------------------
            velocity_target[batch_id, 0, cty_int, ctx_int] = gt_bbox[j, 5]
            brake_target[batch_id, 0, cty_int, ctx_int] = gt_bbox[j, 6].long()
            # -----------------------------------------------------------------
            # Offset target (sub-pixel correction)
            # -----------------------------------------------------------------
            offset_target[batch_id, 0, cty_int, ctx_int] = ctx - ctx_int
            offset_target[batch_id, 1, cty_int, ctx_int] = cty - cty_int
            # Mark this location as valid for loss computation
            wh_offset_target_weight[batch_id, :, cty_int, ctx_int] = 1
    # ---------------------------------------------------------------------
    # Compute normalization factor (number of positive centers)
    # ---------------------------------------------------------------------
    avg_factor = max(1, center_heatmap_target.eq(1).sum())
    # ---------------------------------------------------------------------
    # Pack all targets into a dictionary
    # ---------------------------------------------------------------------
    target_result = dict(center_heatmap_target=center_heatmap_target,
                         wh_target=wh_target,yaw_class_target=yaw_class_target.squeeze(1),
                         yaw_res_target=yaw_res_target,offset_target=offset_target,
                         velocity_target=velocity_target,brake_target=brake_target.squeeze(1),
                         wh_offset_target_weight=wh_offset_target_weight
                         )
    return target_result, avg_factor

