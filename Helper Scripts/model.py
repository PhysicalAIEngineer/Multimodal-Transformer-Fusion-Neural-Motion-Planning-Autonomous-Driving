def gaussian_radius(det_size, min_overlap=0.7):
    """
    Compute the radius of a 2D Gaussian for object heatmap generation.
    Used in CenterNet-style detectors to determine how large the Gaussian
    should be for a given object size, ensuring a minimum IoU overlap.
    Args:
        det_size (tuple): (height, width) of the bounding box
        min_overlap (float): desired minimum IoU overlap (default = 0.7)
    """
    height, width = det_size
    # -------------------------------
    # Case 1: one corner inside
    # Solve quadratic equation: r^2 + (h + w)r + (1 - overlap)/(1 + overlap) * w*h = 0
    # -------------------------------
    a1 = 1
    b1 = height + width
    c1 = width * height * (1 - min_overlap) / (1 + min_overlap)
    # Compute discriminant and radius
    sq1 = torch.sqrt(torch.tensor(b1**2 - 4 * a1 * c1))
    r1 = (b1 + sq1) / 2
    # -------------------------------
    # Case 2: both corners inside
    # Solve: 4r^2 + 2(h + w)r + (1 - overlap) * w*h = 0
    # -------------------------------
    a2 = 4
    b2 = 2 * (height + width)
    c2 = (1 - min_overlap) * width * height
    sq2 = torch.sqrt(torch.tensor(b2**2 - 4 * a2 * c2))
    r2 = (b2 + sq2) / 2
    # -------------------------------
    # Case 3: center inside
    # Solve: 4*overlap*r^2 - 2*overlap*(h + w)r + (overlap - 1)*w*h = 0
    # -------------------------------
    a3 = 4 * min_overlap
    b3 = -2 * min_overlap * (height + width)
    c3 = (min_overlap - 1) * width * height
    sq3 = torch.sqrt(torch.tensor(b3**2 - 4 * a3 * c3))
    r3 = (b3 + sq3) / 2
    # Return the smallest radius that satisfies all conditions
    return min(r1, r2, r3)

