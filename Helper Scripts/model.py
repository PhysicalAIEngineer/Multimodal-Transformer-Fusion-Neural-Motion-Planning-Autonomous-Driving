def simple_test_bboxes(cls_scores, bbox_preds, score_thr=0.05, iou_thr=0.5):
    """
    Perform simple inference for object detection:
    - Select best class per box
    - Filter low-confidence predictions
    - Apply Non-Maximum Suppression (NMS)
    Args:
        cls_scores (Tensor): shape (N, C)
            → class scores (logits or probabilities)
        bbox_preds (Tensor): shape (N, 4)
            → predicted bounding boxes (x1, y1, x2, y2)
        score_thr (float): threshold to filter low-confidence detections
        iou_thr (float): IoU threshold for NMS
    """
    # Select best class for each box
    # - scores → highest class score per box
    # - labels → corresponding class index
    scores, labels = torch.max(cls_scores, dim=1)
    # Filter low-confidence detections
    keep = scores > score_thr
    scores = scores[keep]
    labels = labels[keep]
    boxes = bbox_preds[keep]
    # Apply Non-Maximum Suppression (NMS) removes overlapping boxes with lower scores
    keep = nms(boxes, scores, iou_thr)
    # Return final filtered detections
    return boxes[keep], scores[keep], labels[keep]

