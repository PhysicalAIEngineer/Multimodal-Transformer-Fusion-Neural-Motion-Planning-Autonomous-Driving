def get_topk_from_heatmap(heatmap, K=40):
    """
    Extract top-K keypoints (object centers) from a heatmap.

    Args:
        heatmap (Tensor): shape (B, C, H, W)
                          B = batch size
                          C = number of classes
                          H, W = spatial dimensions
        K (int): number of top detections to keep

    Returns:
        final_scores: (B, K) → top scores
        final_inds: (B, K) → flattened indices
        topk_clses: (B, K) → class IDs
        final_ys: (B, K) → y coordinates
        final_xs: (B, K) → x coordinates
    """
    B, C, H, W = heatmap.shape
    # ----------------------------------------
    # Step 1: Flatten spatial dimensions
    # (B, C, H, W) → (B, C, H*W)
    # ----------------------------------------
    heatmap = heatmap.view(B, C, -1)
    # ----------------------------------------
    # Step 2: Get top-K scores per class
    # ----------------------------------------
    topk_scores, topk_inds = torch.topk(heatmap, K)
    # ----------------------------------------
    # Step 3: Convert flattened indices → (x, y)
    # index = y * W + x
    # ----------------------------------------
    topk_inds = topk_inds % (H * W)
    topk_ys = (topk_inds // W).int()
    topk_xs = (topk_inds % W).int()
    # ----------------------------------------
    # Step 4: Flatten across all classes
    # (B, C, K) → (B, C*K)
    # ----------------------------------------
    topk_scores = topk_scores.view(B, -1)
    topk_inds = topk_inds.view(B, -1)
    topk_ys = topk_ys.view(B, -1)
    topk_xs = topk_xs.view(B, -1)
    # ----------------------------------------
    # Step 5: Select top-K across ALL classes
    # ----------------------------------------
    final_scores, topk_ind = torch.topk(topk_scores, K)
    # ----------------------------------------
    # Step 6: Gather corresponding indices
    # ----------------------------------------
    final_inds = topk_inds.gather(1, topk_ind)
    final_ys = topk_ys.gather(1, topk_ind)
    final_xs = topk_xs.gather(1, topk_ind)
    # ----------------------------------------
    # Step 7: Get class labels
    # Each class contributed K entries → divide index by K
    # ----------------------------------------
    topk_clses = (topk_ind // K).int()
    # Return final detections
    return final_scores, final_inds, topk_clses, final_ys, final_xs

