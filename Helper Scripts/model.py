def gaussian2D(shape, sigma=1):
    """
    Generate a 2D Gaussian kernel.
    Args:
        shape (tuple): (height, width) of the Gaussian kernel
        sigma (float): standard deviation (controls spread of Gaussian)
    """
    # Compute center offsets (so Gaussian is centered at 0,0)
    m, n = [(ss - 1.) / 2. for ss in shape]
    # Create coordinate grid:
    # y: vertical axis, x: horizontal axis
    # meshgrid creates matrices of coordinates
    y, x = torch.meshgrid(
        torch.arange(-m, m + 1),
        torch.arange(-n, n + 1),
        indexing='ij'  # ensures matrix indexing (row, col)
    )
    # Apply 2D Gaussian formula: G(x,y) = exp(-(x^2 + y^2) / (2 * sigma^2))
    h = torch.exp(-(x * x + y * y) / (2 * sigma * sigma))
    # Remove very small values (numerical stability optimization)
    h[h < torch.finfo(h.dtype).eps * h.max()] = 0
    # Return Gaussian kernel
    return h

