class MultiTaskLoss(nn.Module):
    """
    Multi-task loss for detection models.
    Combines:
    - Classification loss (predicting class labels)
    - Regression loss (predicting bounding boxes)
    Total loss = classification loss + regression loss
    """
    def __init__(self):
        # Initialize parent class
        super().__init__()
        # Classification loss:
        # Used for predicting class labels (multi-class classification)
        # Input: logits (not softmax), Target: class indices
        self.cls_loss = nn.CrossEntropyLoss()
        # Regression loss:
        # Used for bounding box prediction (x, y, w, h or x1, y1, x2, y2)
        # SmoothL1 is robust to outliers compared to MSE
        self.reg_loss = nn.SmoothL1Loss()
    def forward(self, pred_cls, gt_cls, pred_box, gt_box):
        """
        Forward pass to compute total loss.
        Args:
            pred_cls: predicted class scores (logits) → shape (N, C)
            gt_cls: ground truth class labels → shape (N,)
            pred_box: predicted bounding boxes → shape (N, 4)
            gt_box: ground truth bounding boxes → shape (N, 4)
        """
        # Compute classification loss
        loss_cls = self.cls_loss(pred_cls, gt_cls)
        # Compute bounding box regression loss
        loss_box = self.reg_loss(pred_box, gt_box)
        # Total loss = sum of both tasks
        return loss_cls + loss_box

