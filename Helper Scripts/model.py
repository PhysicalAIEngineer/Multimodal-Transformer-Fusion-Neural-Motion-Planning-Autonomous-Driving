def draw_gaussian(heatmap, center, radius, k=1):
    """
    Draw a 2D Gaussian on a heatmap at a given center.
    Args:
        heatmap (Tensor): shape (H, W), existing heatmap
        center (tuple): (x, y) coordinates where Gaussian is placed
        radius (int): radius of Gaussian (controls size)
        k (float): scaling factor (peak value multiplier)
    """
    # Diameter of Gaussian kernel
    diameter = 2 * radius + 1
    # Generate Gaussian kernel
    # sigma = diameter / 6 → standard choice for smooth spread
    gaussian = gaussian2D((diameter, diameter), sigma=diameter / 6)
    # Convert center coordinates to integers
    x, y = int(center[0]), int(center[1])
    # Get heatmap dimensions
    height, width = heatmap.shape
    # Compute how much Gaussian fits within heatmap boundaries
    # (handles edge cases when object is near border)
    left, right = min(x, radius), min(width - x, radius + 1)
    top, bottom = min(y, radius), min(height - y, radius + 1)
    # Extract region of heatmap where Gaussian will be applied
    masked_heatmap = heatmap[y - top:y + bottom, x - left:x + right]
    # Extract corresponding region from Gaussian kernel
    masked_gaussian = gaussian[radius - top:radius + bottom,radius - left:radius + right]
    # Ensure valid shapes (avoid empty slices)
    if min(masked_gaussian.shape) > 0 and min(masked_heatmap.shape) > 0:
        # Apply Gaussian using element-wise maximum
        torch.maximum(masked_heatmap, masked_gaussian * k, out=masked_heatmap)
    # Return updated heatmap
    return heatmap

