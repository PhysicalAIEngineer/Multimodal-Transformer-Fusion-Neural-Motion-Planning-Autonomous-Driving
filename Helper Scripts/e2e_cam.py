class AblationLayer(torch.nn.Module):
    def __init__(self):
        # Initialize the parent nn.Module
        super(AblationLayer, self).__init__()
    # Function to generate a binary "objectiveness" mask using SVD (EigenCAM idea)
    def objectiveness_mask_from_svd(self, activations, threshold=0.01):
        """
        Experimental method to decide which regions of the activation map are important (worth ablating) and which are not.
        """
        # Add batch dimension and compute 2D projection (EigenCAM)
        projection = get_2d_projection(activations[None, :])[0, :]
        # Take absolute values to focus on magnitude of importance
        projection = np.abs(projection)
        # Normalize: shift minimum to 0
        projection = projection - projection.min()
        # Normalize: scale to range [0, 1]
        projection = projection / projection.max()
        # Create binary mask: True (1) for important regions, False (0) for less important ones
        projection = projection > threshold
        # Return binary mask
        return projection

    # Function to decide which activation channels should be ablated
    def activations_to_be_ablated(self,activations,ratio_channels_to_ablate=1.0):
      """
      Experimental method to select important activation channels for ablation.
      Steps:
      - Generate a binary importance mask using SVD (EigenCAM idea)
      - Score each channel based on how much it overlaps with important regions
      - Select top channels (and optionally some low ones)
      """
      # If ratio is 1.0 → select ALL channels (no filtering)
      if ratio_channels_to_ablate == 1.0:
        self.indices = np.int32(range(activations.shape[0]))
        return self.indices
      # Generate binary mask of important spatial regions
      projection = self.objectiveness_mask_from_svd(activations)
      # List to store importance scores for each channel
      scores = []
      # Loop through each channel in activations
      for channel in activations:
        # Take absolute values (focus on magnitude)
        normalized = np.abs(channel)
        # Normalize channel values to [0, 1]
        normalized = normalized - normalized.min()
        normalized = normalized / np.max(normalized)
        # Compute score: Measures how much this channel aligns with important regions
        score = (projection * normalized).sum() / normalized.sum()
        # Store the score
        scores.append(score)
      # Convert scores list to NumPy array
      scores = np.float32(scores)
      # Sort channel indices based on scores (ascending order)
      indices = list(np.argsort(scores))
      # Select top channels (highest scores → most important)
      high_score_indices = indices[::-1][: int(len(indices) * ratio_channels_to_ablate)]
      # Optionally also include lowest scoring channels (least important)
      low_score_indices = indices[: int(len(indices) * ratio_channels_to_ablate)]
      # Combine selected indices
      self.indices = np.int32(high_score_indices + low_score_indices)
      # Return indices of channels to be ablated
      return self.indices

    # Function to prepare the next batch of activations for ablation
    def set_next_batch(self,input_batch_index,activations,num_channels_to_ablate):
      """
      function prepares a batch of activations for ablation experiments.
      """
      # Select activations for a single input from the batch
      # Shape: (channels, height, width)
      selected = activations[input_batch_index, :, :, :]
      # Clone to avoid modifying original activations add batch dimension → (1, channels, height, width)
      # Repeat it num_channels_to_ablate times along batch dimension
      # Final shape: (num_channels_to_ablate, channels, height, width)
      self.activations = selected.clone().unsqueeze(0).repeat(num_channels_to_ablate, 1, 1, 1)

    # Function to perform the actual ablation on selected activation channels
    def __call__(self, x):
      # Start with the batch of activations prepared earlier
      output = self.activations
      # Loop through each sample in the batch
      for i in range(output.size(0)):
        # Check if the minimum activation is 0 many networks have ReLU, so min = 0 is common
        if torch.min(output) == 0:
            # Zero out the selected channel(s) for ablation self.indices[i] indicates which channel(s) to ablate
            output[i, self.indices[i], :] = 0
        else:
            # If activations can be negative, use a very negative value this deviates from the original paper but ensures ablation effect
            ABLATION_VALUE = 1e7
            output[i, self.indices[i], :] = torch.min(output) - ABLATION_VALUE
      # Return the batch of activations with selected channels ablated
      return output

class AblationCAM(BaseCAM):
  def __init__(self,model: torch.nn.Module,target_layers: List[torch.nn.Module],
               reshape_transform: Callable = None,ablation_layer: torch.nn.Module = AblationLayer(),
               batch_size: int = 32,ratio_channels_to_ablate: float = 1.0):
    # Initialize the parent BaseCAM class
    super(AblationCAM, self).__init__(model, target_layers, reshape_transform)
    # Batch size for ablation experiments activations may be repeated and processed in batches for efficiency
    self.batch_size = batch_size
    # Layer that performs the actual ablation contains methods for generating masks and zeroing out channels
    self.ablation_layer = ablation_layer
    # Fraction of channels to ablate in each experiment
    # 1.0 → all channels; smaller values → only top-ranked channels
    self.ratio_channels_to_ablate = ratio_channels_to_ablate

  # Helper method to save raw activations from the target layer
  def save_activation(self, module, input, output):
    """
    Store the output of a target layer for later use in ablation.
    """
    self.activations = output

  # Assemble scores for all channels after ablation experiments
  def assemble_ablation_scores(self,new_scores: list,original_score: float,ablated_channels: np.ndarray,number_of_channels: int):
    """
    Create a final array of channel importance scores:
    - For channels that were actually ablated, use the new scores from the experiment
    - For channels that were skipped, assign the original model score
    """
    # Pointer to iterate over ablated_channels
    index = 0
    # List to store final scores
    result = []
    # Sort the indices of ablated channels to maintain correct order
    sorted_indices = np.argsort(ablated_channels)
    ablated_channels = ablated_channels[sorted_indices]
    new_scores = np.float32(new_scores)[sorted_indices]
    # Loop over all channels
    for i in range(number_of_channels):
      if index < len(ablated_channels) and ablated_channels[index] == i:
        # If this channel was ablated, use its experimental score
        weight = new_scores[index]
        index += 1
      else:
        # If skipped, use the original score
        weight = original_score
      result.append(weight)
    # Return final channel-wise importance scores
    return result

  # Compute CAM weights using Ablation-CAM (gradient-free method)
  def get_cam_weights(self,input_tensor: torch.Tensor,target_layer: torch.nn.Module,
                      targets: List[Callable],activations: torch.Tensor,grads: torch.Tensor):
    # Cache original activations of the target layer
    handle = target_layer.register_forward_hook(self.save_activation)
    with torch.no_grad():
      # Forward pass
      outputs = self.model(input_tensor)
      # Remove hook after forward
      handle.remove()
      # Compute original target scores for each input in batch
      original_scores = np.float32([target(output).cpu().item() for target, output in zip(targets, outputs)])
    # Replace the target layer with the ablation layer this layer allows systematically zeroing out channels
    ablation_layer = self.ablation_layer
    replace_layer_recursive(self.model, target_layer, ablation_layer)
    # Total channels is target layer
    number_of_channels = activations.shape[1]
    # list to store channel importance scores
    weights = []
    # Perform gradient-free ablation experiments
    with torch.no_grad():
      # Loop over each input in the batch
      for batch_index, (target, tensor) in enumerate(zip(targets, input_tensor)):
        # Scores after ablating channels for this input
        new_scores = []
        # Repeat the input tensor to process multiple ablations in batch
        batch_tensor = tensor.repeat(self.batch_size, 1, 1, 1)
        # Decide which channels to ablate
        channels_to_ablate = ablation_layer.activations_to_be_ablated(activations[batch_index, :], self.ratio_channels_to_ablate)
        number_channels_to_ablate = len(channels_to_ablate)
        # Process ablations in mini-batches
        for i in tqdm.tqdm(range(0, number_channels_to_ablate, self.batch_size)):
          # Adjust batch size if near the end
          if i + self.batch_size > number_channels_to_ablate:
            batch_tensor = batch_tensor[:(number_channels_to_ablate - i)]
          # Prepare the next batch of activations with channels to ablate
          ablation_layer.set_next_batch(input_batch_index=batch_index,
                                        activations=self.activations,
                                        num_channels_to_ablate=batch_tensor.size(0)
                                        )
          # Forward pass with ablated activations, compute new target scores
          score = [target(o).cpu().item() for o in self.model(batch_tensor)]
          new_scores.extend(score)
          # Remove already processed indices from ablation_layer
          ablation_layer.indices = ablation_layer.indices[batch_tensor.size(0):]
        # Combine scores for ablated and skipped channels
        new_scores = self.assemble_ablation_scores(new_scores,original_scores[batch_index],
                                                   channels_to_ablate,number_of_channels)
        # Append this input's weights to the overall list
        weights.extend(new_scores)
      # Convert to NumPy array and reshape to (batch, channels)
      weights = np.float32(weights)
      weights = weights.reshape(activations.shape[:2])
      # Normalize weights: relative drop compared to original score
      original_scores = original_scores[:, None]  # Shape: (batch, 1)
      weights = (original_scores - weights) / original_scores
      # Restore the original model (replace ablation layer back)
      replace_layer_recursive(self.model, ablation_layer, target_layer)
      # Return final CAM weights for each channel
      return weights

# Helper class to define a target for a planning network it computes a loss between the predicted waypoints and a reference target
class PlannerTarget:
    def __init__(self, target_wp):
        self.target_wp = target_wp
        if torch.cuda.is_available():
            self.target_wp = self.target_wp.cuda()
    def __call__(self, model_output):
        """
        Compute the L1 loss between the model's predicted waypoints and the target waypoints.
        """
        _, debug_outputs = model_output
        # Convert predicted waypoints (numpy) to tensor, compute absolute differences
        l1_loss = torch.mean(torch.abs(torch.from_numpy(debug_outputs['pred_wp']) - self.target_wp))
        return l1_loss





