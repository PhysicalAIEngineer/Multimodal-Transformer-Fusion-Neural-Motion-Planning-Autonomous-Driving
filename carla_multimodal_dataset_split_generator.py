import os
import random

# Root folder of your datase
DATASET_DIR = "dataset"
# Use RGB folder as reference to get
REFERENCE_FOLDER = "rgb"
# 70% training data
TRAIN_RATIO = 0.7
# Random seed for reproducibility
SEED = 42
# Fix randomness (same split every time)
random.seed(SEED)
# Path to reference folder (dataset/rgb)
ref_path = os.path.join(DATASET_DIR, REFERENCE_FOLDER)
# Get all files
files = sorted(os.listdir(ref_path))
# Extract (remove file extension → "000001")
frames = [os.path.splitext(f)[0] for f in files]
# Print total number of frames
print(f"Total frames found: {len(frames)}")
# Randomly shuffle  for unbiased train/val split
random.shuffle(frames)
# Compute split index (70% of total frames)
split_idx = int(TRAIN_RATIO * len(frames))
# Split into train and validation sets
train_frames = frames[:split_idx]
val_frames = frames[split_idx:]
# Print number of frames in each set
print(f"Train: {len(train_frames)}")
print(f"Val: {len(val_frames)}")
# File paths for saving split lists
train_file = os.path.join(DATASET_DIR, "train.zip")
val_file = os.path.join(DATASET_DIR, "val.zip")
# Save train
with open(train_file, "w") as f:
    for frame in train_frames:
        f.write(frame + "\n")
# Save validation
with open(val_file, "w") as f:
    for frame in val_frames:
        f.write(frame + "\n")

